   "html": "<p>The set of mechanisms allowing vibration at the free edge of the vocal fold, transforming aerodynamic energy into acoustic energy. The sound produced is immediately modified and filtered by the supralaryngeal air cavities to become vowels and consonants: the bucco-pharyngeal resonators.</p><p><strong>The voice</strong> is characterised by three acoustic parameters: <strong>frequency</strong>, in Hertz, depending on the vibration speed of the vocal folds; <strong>intensity</strong>, in dB, depending on the force of pulmonary expiration (subglottic pressure); and <strong>pitch</strong>, depending on the accommodation of the vocal folds but especially on the shape of the supralaryngeal cavities.</p><p><strong>Respiratory changes.</strong> During phonation the expiratory time lengthens and becomes active, the inspiratory time shortens, the mobilised air volumes are greater and expiratory lung pressures increase. The expiratory blow creates a subglottic pressure that overcomes the resistance of the vocal cords.</p><p><strong>The vibratory cycle.</strong> 1. Putting into phonatory position: the folds close as the arytenoids come together. 2. Opening: when the subglottic pressure overcomes the muscular and elastic resistance, a puff of air passes at high speed, an acoustic impulse. 3. Closure of the folds.</p><p><strong>The supralaryngeal cavities.</strong> Filter role: resonance and enrichment of certain frequencies or suppression of others, with two areas of particular enhancement, the pharynx and the oral cavity. The basic laryngeal frequency is enriched with harmonics giving the pitch. Articulation role: through the tongue, pharyngolarynx, jaws, lips and soft palate. Dry or cold ambient air can change the voice through mucous changes in the walls.</p><p><strong>Mechanism, step by step.</strong> 1. The vocal cords are kept adducted. 2. Infraglottic air pressure is generated by exhaled air from the lungs. 3. The force of air opens the cords and is released as small puffs. 4. Moving air passing through the cords makes them vibrate, producing sound. 5. Sound is amplified by the mouth, pharynx, oesophagus and nose. 6. Sound is converted into speech by the lips, tongue, palate, pharynx and teeth.</p><p>Vowels are voiced in the larynx by vibration of the vocal folds; consonants are produced by the intrinsic muscles of the tongue. Loudness depends on the amplitude of vibration, pitch on the frequency. Male cords are usually longer, so they vibrate with greater amplitude but lower frequency: louder but lower pitched.</p>"
