   "html": "<p>Initiated by cell activation (mast cells +++) and histamine release. <strong>Congestion</strong>: arteriolar then capillary vasodilatation and slowing of flow → redness and heat. <strong>Inflammatory oedema</strong>: endothelial retraction opens intercellular gaps, raised hydrostatic and permeability → protein-rich exudate → swelling and pain. The oedema dilutes toxins, brings immunoglobulins/complement (opsonins) and fibrinogen (fibrin barrier), and slows flow to favour diapedesis — but can be harmful by volume or site (laryngeal, cerebral, acute pulmonary oedema). <strong>Leukocyte diapedesis</strong>: slowing of flow → margination → rolling and adhesion (selectins) → passage between endothelial cells with basement-membrane degradation → migration by <strong>chemotaxis</strong> along a gradient (bacterial products, necrotic tissue, complement, arachidonic-acid metabolites). Neutrophils first (6–24 h), then monocytes (24–48 h); lymphocytes may come first in viral infection, eosinophils in some hypersensitivity.</p>"
