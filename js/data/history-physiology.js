   "html": "<p><strong>William Harvey</strong> (17th c., English) showed blood circulates through lungs and body rather than being constantly renewed, and that the <strong>heart is a pump</strong>, by mathematics and experiment — the first serious challenge to Galen and the start of experimental physiology. Galileo: measure all that is measurable. <strong>René Descartes</strong>: mind-body dualism, explaining life by mechanical laws without denying God; animal spirits as fast particles in nerves; the soul only human, in the pineal gland; the heart heats rather than pumps; <strong>iatromechanism</strong> — the human as a clock. Critics noted passions and emotions link mind and body. <strong>Iatrochemistry</strong>: life as combustion — John Mayow's candle and mouse: breathable air and burnable air are identical, life as combustion of carbon with oxygen, heat as life. <strong>Luigi Galvani</strong> (18th c.) discovered animal electricity: current produces reflex movement.</p>"
